"""Build docs/console_capture.md from the verbatim files written by capture_console.py.

The three console captures are inserted unedited. The move timeline table matches the move script
hard-coded in capture_console.py; update both together if the script changes.

Run: python3 src/tests/build_capture_doc.py [capture_dir] [output_md]
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
cap = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "capture_output")
out = sys.argv[2] if len(sys.argv) > 2 else os.path.join(REPO, "docs", "console_capture.md")

srv, a, b = (open(os.path.join(cap, f"{n}.txt")).read().rstrip() for n in ("server", "alice", "bob"))
port = re.search(r"--port (\d+)", srv).group(1)
date = re.search(r"^(\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)", srv.splitlines()[1]).group(1)

doc = f"""# Console Capture: Two-Client Gameplay Session

Verbatim terminal output from one server and two client sessions playing a complete Connect-4 game
over TCP. Generated by the AI agent during testing (see `agent_workflow.md`, Session 4).
Regenerate with `src/tests/capture_console.py` then `src/tests/build_capture_doc.py`.

| Field | Value |
|---|---|
| Captured | {date} MST |
| Host | Local test machine, loopback `127.0.0.1` (not yet the CML topology) |
| Server | `python3 server.py --port {port}` (single-threaded `selectors` loop) |
| Client 1 | `python3 client.py -i localhost -p {port} --name Alice` (resolves the DNS name with `gethostbyname`) |
| Client 2 | `python3 client.py -i 127.0.0.1 -p {port} --name Bob` |
| Transport | TCP, `socket.socket(socket.AF_INET, socket.SOCK_STREAM)` on both server and client |
| Framing | 4-byte big-endian length prefix + compact JSON |
| Turns played | 7 (game ends in a vertical win for Player 1) |

**How it was captured:** each client ran in its own pseudo-terminal (pty), so the output is exactly
what a player sees, including the input they type (echoed after each `(q to quit):` prompt).
A driver script typed the moves only after each prompt appeared. Server log lines go to stderr.
Nothing below has been edited.

## Move Timeline

| Turn | Player | Input | Result |
|---|---|---|---|
| 1 | Player 1 (Alice, X) | `3` | X lands at bottom of column 3 |
| 2 | Player 2 (Bob, O) | `9`, then `2` | `9` rejected locally (range 0-6); O in column 2 |
| 3 | Player 1 (Alice, X) | `3` | X stacks in column 3 |
| 4 | Player 2 (Bob, O) | `4` | O in column 4 |
| 5 | Player 1 (Alice, X) | `3` | X stacks in column 3 (three in a row) |
| 6 | Player 2 (Bob, O) | `2` | O stacks in column 2 |
| 7 | Player 1 (Alice, X) | `3` | Four in a row vertically: **Alice wins** |
| End | both | `n` | Rematch declined, server sends `CLOSE`, returns to matchmaking |

## Client 1 (Alice, Player 1, X)

```text
{a}
```

## Client 2 (Bob, Player 2, O)

```text
{b}
```

## Server Console

Each line is one FSM transition or connection event. One valid move appears as
`PLAYER_TURN → EVALUATE_PLACEMENT → STATE_UPDATE → PLAYER_TURN`, and the session ends with
`GAME_OVER → GAME_RESULT → RESULT_SENT → MATCHMAKING`. The final line is the server shutting
down on Ctrl+C (SIGINT).

```text
{srv}
```

## Requirements Shown

| Requirement | Where it appears above |
|---|---|
| TCP sockets via `socket.socket(AF_INET, SOCK_STREAM)` | Server listener (`server.py` `open_listener`) and client (`client.py` `main`); both connections are accepted in the server log |
| Two client sessions connected to the server | Two `accepted connection from 127.0.0.1:…` lines; `GAME START` in both clients |
| At least 3 turns of gameplay | 7 turns, numbered `Turn 1` … `Turn 7` |
| Clean, human-readable board | Grid with column numbers 0-6, blank empty cells, `X`/`O` discs |
| Clear turn status | `>>> Your Turn` and `... Waiting for Player 2 (Bob)...` / `... Waiting for Player 1 (Alice)...` after every move |
| Score summary | `Score` line at game start and game over (`Player 1 (Alice, X): 1 / Player 2 (Bob, O): 0 / Draws: 0`) |
| Input validation | Bob's `9` rejected with `Please enter a whole number from 0 to 6.` |
| Synchronized state | Both clients show the same board after every move; one `STATE` per move |
| Graceful end of session | `Play again? (y/n): n` → `Server closed the session: session finished` |
"""

with open(out, "w") as f:
    f.write(doc)
print(f"wrote {out} ({len(doc.splitlines())} lines)")
